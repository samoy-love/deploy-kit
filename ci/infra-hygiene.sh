#!/usr/bin/env bash
# Не выпускать наружу подробности о том, где физически стоит боевой сервер.
#
# ЗАЧЕМ. Репозитории публичные. Сам факт, что прод живёт на конкретном железе в
# конкретном месте, плюс адреса внутренних мостов и имена сетевых железок — это
# разведданные для того, кто захочет туда постучаться. Пароли и ключи ловит
# отдельный гейт секретов; здесь ловится топология.
#
# ЧТО ПРОВЕРЯЕТСЯ: добавленные в PR строки, сообщения коммитов PR, заголовок и
# описание PR. Источники равноправны: утечка в описании PR видна ровно так же,
# как утечка в коде.
#
# ЧЕГО ПРОВЕРКА НАМЕРЕННО НЕ ЛОВИТ:
#   * «домашний экран» — это PWA, а не сервер;
#   * «домашняя директория», «домашние сборки Windows» — обычные термины;
#   * частные адреса 192.168.x и 10.x сами по себе: они сплошь и рядом стоят в
#     тестах как примеры, и запрет дал бы ложных срабатываний больше, чем
#     находок. Ловится не диапазон, а связка «домашний + сервер».
#
# Две грабли, на которых эта проверка уже спотыкалась:
#   1. `\w` в PCRE по умолчанию не считает кириллицу словом — нужен префикс
#      (*UTF)(*UCP), иначе «домашней машине» не находится вовсе.
#   2. Конвейер `printf | scan` уводит функцию в подоболочку, и выставленный в
#      ней флаг ошибки наружу не возвращается — гейт молча зеленеет. Поэтому
#      текст кладётся во временный файл, а функция читает файл.
export LC_ALL=C.UTF-8
set -Eeuo pipefail

PATTERNS=(
  '77\.37\.166\.207'                                    # публичный адрес прода
  '10\.22\.42\.[0-9]{1,3}'                              # адреса внутреннего моста
  '(*UTF)(*UCP)домашн\w*\s+(сервер|машин|раннер|сет|LAN|железо|железе|железу|канал|IP|адрес)\w*'
  '(*UTF)(*UCP)(сервер|раннер|машина)\w*\s+(стоит\s+)?дома\b'
  '\b(OpenWrt|incusbr0|Forkop|Zapret|NanoPi)\b'         # имена сетевых железок и обходов
  '(*UTF)(*UCP)в\s+(жилой\s+комнате|квартире)'          # где стоит
)

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
fail=0

# $1 — как назвать источник в отчёте, $2 — файл с текстом
scan_file() {
    local label="$1" file="$2" p
    [ -s "$file" ] || return 0
    for p in "${PATTERNS[@]}"; do
        if grep -nPi -- "$p" "$file" > "$TMP/hits" 2>/dev/null && [ -s "$TMP/hits" ]; then
            echo "::error::$label: подробности инфраструктуры"
            head -5 "$TMP/hits" | sed 's/^/    /'
            fail=1
        fi
    done
}

BASE="${1:-}"
HEAD_REF="${2:-HEAD}"

if [ -n "$BASE" ]; then
    # Только добавленные строки: то, что уже лежало в репозитории, этот PR
    # чинить не обязан — иначе гейт заблокирует всё подряд.
    # Сама проверка из сканирования исключена: её шаблоны — это ровно те
    # строки, которые она ищет, и без исключения она валит собственный PR.
    git diff --unified=0 "$BASE...$HEAD_REF" -- . ':(exclude)ci/infra-hygiene.sh' ':(exclude).github/workflows/infra-hygiene.yml' \
      | grep -E '^\+' | grep -vE '^\+\+\+' | sed 's/^\+//' > "$TMP/added" || true
    scan_file "изменённые строки" "$TMP/added"

    git log --format='%s%n%b' "$BASE..$HEAD_REF" > "$TMP/commits" || true
    scan_file "сообщения коммитов" "$TMP/commits"
fi

# Заголовок и описание PR приходят через окружение — в git их нет.
printf '%s\n%s\n' "${PR_TITLE:-}" "${PR_BODY:-}" > "$TMP/pr"
scan_file "заголовок/описание PR" "$TMP/pr"

if [ "$fail" -ne 0 ]; then
    cat >&2 <<'MSG'

Как чинить — заменить формулировку на нейтральную:
    «домашний сервер»   -> «боевой сервер»
    «домашний раннер»   -> «собственный раннер»
    «домашняя сеть/LAN» -> «внутренняя сеть»
    адреса и имена железок -> убрать совсем
Ложное срабатывание чинится уточнением шаблона в ci/infra-hygiene.sh,
а не исключением в вызывающем workflow.
MSG
    exit 1
fi
echo "инфраструктура: чисто"
