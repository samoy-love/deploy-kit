#!/usr/bin/env bash
# Прогон prune_releases (server/lib.sh) по настоящему каталогу релизов.
#
#   ci/prune-test.sh
#
# ЗАЧЕМ ЭТОТ ФАЙЛ. prune_releases — единственное место выкатки, которое
# выполняет `rm -rf` по каталогу, вычисленному из состояния файловой системы.
# Ошибка здесь стоит не косметики: снесённый каталог живого релиза оставляет
# симлинк current указывать в пустоту, и прод отдаёт 404 при формально
# успешной выкатке. Прочитать такую функцию глазами мало — половина её
# поведения это поведение find, sort и readlink, которых в момент чтения нет.
#
# Функция берётся НАСТОЯЩАЯ, через `source server/lib.sh`: копия в тесте
# проверяла бы копию.
#
# Сценарий, ради которого функция и переписана, — третий: откат не создаёт
# каталога, он переводит симлинк на СТАРЫЙ. mtime у того старого недельной
# давности, то есть в очереди на удаление он первый. До защиты следующая же
# выкатка этой цели сносила живой прод.

set -uo pipefail

KIT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
LIB="$KIT/server/lib.sh"
[[ -f "$LIB" ]] || { echo "не найден: $LIB" >&2; exit 1; }

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

pass=0; fail=0; skipped=0
# Имена с префиксом: lib.sh приносит свои ok/log/warn, и подменять их нельзя —
# их вывод здесь тоже проверяется.
t_ok()   { printf '  \033[32m✓\033[0m %s\n' "$*"; pass=$(( pass + 1 )); }
t_bad()  { printf '  \033[31m✗\033[0m %s\n' "$*" >&2; fail=$(( fail + 1 )); }
t_skip() { printf '  \033[33m—\033[0m %s\n' "$*"; skipped=$(( skipped + 1 )); }
t_case() { printf '\n\033[1m%s\033[0m\n' "$*"; }

# shellcheck source=/dev/null
source "$LIB"

# Настоящие симлинки есть не везде: в Git Bash под Windows `ln -s` без права
# на создание ссылок молча делает копию, и разыменование перестаёт что-либо
# значить. Случай с симлинками тогда пропускается ВСЛУХ, а сама защита всё
# равно проверяется — тем же вызовом, но прямыми путями (случай 3б). На
# раннере ubuntu пропусков не бывает, и строка в конце об этом напоминает.
SYMLINKS=0
if ln -sfn "$TMP" "$TMP/.probe" 2>/dev/null && [[ -L "$TMP/.probe" ]]; then
    SYMLINKS=1
fi
rm -f "$TMP/.probe" 2>/dev/null || true

# Каталог релизов с заданным порядком mtime: rel-1 самый старый.
make_root() { # make_root <имя> <сколько релизов>
    local root="$TMP/$1" n="$2" i
    rm -rf "$root"; mkdir -p "$root/releases"
    for (( i = 1; i <= n; i++ )); do
        mkdir -p "$root/releases/rel-$i"
        touch -d "2026-08-0$i" "$root/releases/rel-$i"
    done
    printf '%s' "$root"
}

listing() { ls "$1/releases" | sort | tr '\n' ' '; }

# --------------------------------------------------------------------------
t_case "1. Без защиты уходят самые старые, остаётся KEEP"
R="$(make_root plain 7)"
prune_releases "$R/releases" 5 >/dev/null 2>&1
[[ "$(listing "$R")" == "rel-3 rel-4 rel-5 rel-6 rel-7 " ]] \
    && t_ok "осталось пять новейших" \
    || t_bad "осталось: $(listing "$R")"

t_case "2. Вызов из двух аргументов работает как раньше"
R="$(make_root legacy 3)"
prune_releases "$R/releases" 2 >/dev/null 2>&1
[[ "$(listing "$R")" == "rel-2 rel-3 " ]] \
    && t_ok "совместимость со старой сигнатурой" \
    || t_bad "осталось: $(listing "$R")"

t_case "3. Живой релиз не удаляется, даже если он самый старый"
# Ровно состояние после `rollback.sh --to rel-1`: current смотрит на самый
# старый каталог, previous — на предпоследний.
if (( SYMLINKS )); then
    R="$(make_root rolledback 7)"
    ln -sfn "$R/releases/rel-1" "$R/current"
    ln -sfn "$R/releases/rel-6" "$R/previous"
    OUT="$(prune_releases "$R/releases" 5 "$R/current" "$R/previous" 2>&1)"
    [[ -d "$R/releases/rel-1" ]] \
        && t_ok "каталог живого релиза на месте" \
        || t_bad "живой релиз удалён — прод остался бы с симлинком в пустоту"
    [[ -d "$(readlink -f "$R/current")" ]] \
        && t_ok "current указывает на существующий каталог" \
        || t_bad "current указывает в пустоту"
    [[ "$OUT" == *"не удаляю"* ]] \
        && t_ok "о пропуске сказано вслух" \
        || t_bad "пропуск живого релиза прошёл молча"
    [[ ! -d "$R/releases/rel-2" ]] \
        && t_ok "незащищённый старый релиз при этом удалён" \
        || t_bad "не удалено ничего — чистка перестала работать"
else
    t_skip "настоящих симлинков в этом окружении нет — защита проверена ниже прямыми путями"
fi

t_case "3б. То же самое без симлинков: защищён самый старый каталог"
R="$(make_root protected 7)"
OUT="$(prune_releases "$R/releases" 5 "$R/releases/rel-1" "$R/releases/rel-6" 2>&1)"
[[ -d "$R/releases/rel-1" ]] \
    && t_ok "защищённый каталог на месте" \
    || t_bad "защищённый каталог удалён"
[[ "$OUT" == *"не удаляю"* ]] \
    && t_ok "о пропуске сказано вслух" \
    || t_bad "пропуск прошёл молча"

t_case "4. Защита не мешает удалять остальные"
[[ ! -d "$R/releases/rel-2" ]] \
    && t_ok "незащищённый старый релиз удалён" \
    || t_bad "не удалено ничего — чистка перестала работать"
[[ -d "$R/releases/rel-7" ]] \
    && t_ok "новые релизы не тронуты" \
    || t_bad "удалён новый релиз"

t_case "5. Пустые и несуществующие пути защиты не ломают вызов"
R="$(make_root empties 7)"
prune_releases "$R/releases" 5 "" "$R/current-нет" >/dev/null 2>&1
[[ "$(listing "$R")" == "rel-3 rel-4 rel-5 rel-6 rel-7 " ]] \
    && t_ok "пустой аргумент — не защита и не ошибка" \
    || t_bad "осталось: $(listing "$R")"

t_case "6. Нечего чистить — ничего и не трогаем"
R="$(make_root few 3)"
prune_releases "$R/releases" 5 >/dev/null 2>&1
[[ "$(listing "$R")" == "rel-1 rel-2 rel-3 " ]] \
    && t_ok "релизов меньше KEEP — каталог не тронут" \
    || t_bad "осталось: $(listing "$R")"

t_case "7. Нет каталога релизов — не ошибка"
prune_releases "$TMP/нет-такого/releases" 5 >/dev/null 2>&1 \
    && t_ok "тихо выходит с нулём" \
    || t_bad "код возврата ненулевой"

printf '\nитого: \033[32m%d\033[0m прошло, \033[31m%d\033[0m провалено, \033[33m%d\033[0m пропущено\n' \
    "$pass" "$fail" "$skipped"
(( skipped )) && printf 'Пропущенные проверки — это НЕ зелёный прогон: на раннере они обязаны пройти.\n'
(( fail == 0 ))
