#!/usr/bin/env bash
# Прогон запрета выкатки задом наперёд: monotonic_gate (server/lib.sh) и то,
# как его зовут release.sh и rollback.sh.
#
#   ci/monotonic-test.sh
#
# ЗАЧЕМ ЭТОТ ФАЙЛ. Прогоны в main больше не отменяются, а становятся в очередь,
# и у этого есть обратная сторона: на прод может приехать законно собранный, но
# СТАРЫЙ релиз. Способов ровно три, и все три штатные — повторный запуск давнего
# прогона в интерфейсе GitHub, workflow_dispatch на старом ref, задача,
# отвисевшая в очереди дольше следующей за ней. Выкатка при этом выглядит
# обычной: артефакт настоящий, проверки зелёные, симлинк переключился. На проде
# молча пропадает функциональность вместе со списком изменений, и заметить это
# можно только по жалобам.
#
# Проверять такое глазами бесполезно: вся суть в том, КУДА поставлена проверка и
# кого она НЕ должна задеть. Отсюда две половины прогона:
#
#   1. поведение monotonic_gate — функция берётся настоящая, через
#      `source server/lib.sh`. Копия кода в тесте проверяла бы копию;
#   2. места вызова в release.sh и rollback.sh — читаются из исходников. Самая
#      дорогая ошибка здесь не в самой функции, а в её расстановке: проверка,
#      уехавшая внутрь switch_symlink, запретила бы АВТООТКАТ, то есть починку
#      прода в момент аварии. Такую ошибку не видно ни в одном зелёном тесте
#      функции.
#
# Настоящей выкатки здесь нет и быть не может: release.sh требует root, flock,
# systemd и корень внутри /opt|/var/www. Граница прогона честная — он отвечает
# за решение шлюза и за его расстановку, но не за выкатку целиком.
#
# Вызов воспроизводит боевой контекст дословно: `set -Eeuo pipefail`, как в
# release.sh. Проверка обязана либо пропустить, либо внятно отказать — но не
# уронить скрипт где-то посередине.

set -uo pipefail

KIT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
LIB="$KIT/server/lib.sh"
REL="$KIT/server/release.sh"
RB="$KIT/server/rollback.sh"
for f in "$LIB" "$REL" "$RB"; do
    [[ -f "$f" ]] || { echo "не найден: $f" >&2; exit 1; }
done

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

pass=0; fail=0
# Имена с префиксом: lib.sh приносит свои ok/log/warn, и подменять их нельзя —
# именно их вывод здесь и проверяется.
t_ok()   { printf '  \033[32m✓\033[0m %s\n' "$*"; pass=$(( pass + 1 )); }
t_bad()  { printf '  \033[31m✗\033[0m %s\n' "$*" >&2; fail=$(( fail + 1 )); }
t_case() { printf '\n\033[1m%s\033[0m\n' "$*"; }

# shellcheck source-path=SCRIPTDIR
# shellcheck source=../server/lib.sh
source "$LIB"
set +e   # lib.sh включает errexit для себя; тесту он мешает считать провалы

OUT="$TMP/out"
RC=0

# Боевой контекст: errexit включён, функция зовётся как в release.sh — без
# `||`, то есть отказ обязан вынести весь процесс, а не вернуть код в никуда.
run_gate() { # run_gate <новый> <живой> <разрешить старее>
    RC=0
    ( set -Eeuo pipefail; monotonic_gate "$1" "$2" "$3" ) >"$OUT" 2>&1 || RC=$?
}

expect_rc()   { [[ "$RC" == "$1" ]] && t_ok "код возврата $1: $2" || t_bad "$2: код $RC, ожидался $1"$'\n'"    $(cat "$OUT")"; }
expect_has()  { grep -qF -- "$1" "$OUT" && t_ok "сказано «$1»" || t_bad "не сказано «$1», вывод:"$'\n'"$(cat "$OUT")"; }
expect_hasnt(){ grep -qF -- "$1" "$OUT" && t_bad "не должно быть «$1», вывод:"$'\n'"$(cat "$OUT")" || t_ok "нет «$1»"; }
expect_quiet(){ [[ ! -s "$OUT" ]] && t_ok "молчит" || t_bad "лишний вывод на штатном пути:"$'\n'"$(cat "$OUT")"; }

NEW="release-20260803-120000-1a2b3c4"
OLD="release-20260802-134500-abc1234"

# --------------------------------------------------------------------------
t_case "1. Релиз старше живого отвергается, и симлинк остаётся на живом"

run_gate "$OLD" "$NEW" 0
# Код именно GATE_REJECT: вызывающая сторона (bin/deploy, workflow) по нему
# отличает «шлюз не пустил, прод цел» от «выкатка сломалась посередине».
expect_rc "$GATE_REJECT" "старый релиз поверх нового"
expect_has "СТАРШЕ"
# Отказ обязан объяснять, что делать: молчаливый провал заставляет человека
# перезапускать прогон снова и снова, каждый раз с тем же исходом.
expect_has "--allow-older"
expect_has "$NEW"

t_case "1a. Отказ виден человеку, а не только коду возврата"
# Проверка отдельным случаем, потому что в этом вся разница между «выкатка не
# поехала» и «выкатка тихо не поехала». Второе с очередью прогонов выглядит
# как успешный деплой, после которого на проде ничего не изменилось.
[[ -s "$OUT" ]] && t_ok "отказ напечатан" || t_bad "отказ ничего не напечатал"
grep -q 'СТАРШЕ' "$OUT" && t_ok "названа причина" || t_bad "причина не названа"

# --------------------------------------------------------------------------
t_case "2. С разрешённым движением назад проходит (это откат)"

run_gate "$OLD" "$NEW" 1
expect_rc 0 "откат назад"
expect_has "движение назад разрешено явно"

t_case "2a. Флаг --allow-older известен rollback.sh"
# Отказ монотонности печатает готовую команду с этим флагом, и человек
# копирует её в момент аварии. Неизвестный аргумент уронил бы откат на разборе
# командной строки — то есть сообщение о неверной выкатке стоило бы прода.
# Проверяется поведением: --root заведомо негодный, интересует только то, что
# скрипт спотыкается НЕ на флаге.
"$BASH" "$RB" --app dk-test-nonexistent --allow-older --list >"$OUT" 2>&1
grep -qF 'неизвестный аргумент' "$OUT" \
    && t_bad "rollback.sh не знает --allow-older — команда из отказа не работает" \
    || t_ok "rollback.sh принимает --allow-older"

# --------------------------------------------------------------------------
t_case "3. Первая выкатка цели: живого релиза ещё нет"

# Самый дорогой ложный отказ: новая цель не выкатилась бы никогда, причём
# сообщение говорило бы про «релиз старше живого», которого не существует.
run_gate "$NEW" "" 0
expect_rc 0 "живого релиза нет"
expect_has "первая выкатка"
expect_hasnt "СТАРШЕ"

# --------------------------------------------------------------------------
t_case "4. Движение вперёд не мешает и не шумит"

run_gate "$NEW" "$OLD" 0
expect_rc 0 "новый релиз поверх старого"
expect_quiet

t_case "4a. Тот же каталог релиза — не движение назад"
# Перевыкатка поверх текущего решается версионным шлюзом
# (--allow-same-version), и монотонность обязана пропускать её молча, иначе на
# один случай приходилось бы два разных отказа с разными флагами.
run_gate "$NEW" "$NEW" 0
expect_rc 0 "тот же релиз"
expect_quiet

t_case "4b. Секунда та же, коммиты разные — тоже не назад"
run_gate "release-20260803-120000-1a2b3c4" "release-20260803-120000-9f8e7d6" 0
expect_rc 0 "одинаковое время сборки"

t_case "4c. Ведущие нули в дате и времени не ломают арифметику"
# 08 и 09 — не восьмеричное: без 10# сравнение падало бы с «value too great
# for base», причём ровно девять месяцев в году и девять часов в сутках.
run_gate "release-20260908-093000-aaa1111" "release-20260908-083000-bbb2222" 0
expect_rc 0 "утро сентября, движение вперёд"
run_gate "release-20260908-083000-bbb2222" "release-20260908-093000-aaa1111" 0
expect_rc "$GATE_REJECT" "утро сентября, движение назад"

# --------------------------------------------------------------------------
t_case "5. Неразбираемое имя релиза НЕ блокирует выкатку"

# Закрытая проверка («всё непонятное — отказ») годится там, где отказ дешёв.
# Здесь он стоит цели, которая встала навсегда: имя не по образцу — это не
# движение назад, а неизвестный порядок. Поэтому предупреждение, а не отказ.
run_gate "hotfix-manual" "$NEW" 0
expect_rc 0 "новое имя не разбирается"
expect_has "не разобрать время сборки"

run_gate "$NEW" "hotfix-manual" 0
expect_rc 0 "живое имя не разбирается"
expect_has "не разобрать время сборки"

run_gate "hotfix-manual" "hotfix-old" 0
expect_rc 0 "оба имени не разбираются"
expect_has "проверка пропущена"

t_case "5a. Семверные имена релизов монотонность не судит"
# Отдельным случаем, потому что это осознанная граница, а не недосмотр:
# сравнение по времени сборки семверу не подходит вовсе, а разбором схем
# занимается compare_versions в версионном шлюзе. Молча пропустить нельзя —
# и «отказать» тоже нельзя.
run_gate "v1.2.3" "v1.3.0" 0
expect_rc 0 "семвер назад"
expect_has "не разобрать время сборки"

# --------------------------------------------------------------------------
t_case "6. Проверка стоит на пути выкатки, а НЕ на пути отката"

# Самая дорогая ошибка расстановки. Проверка, попавшая внутрь switch_symlink
# или внутрь rollback(), запретила бы автооткат: прод остался бы на сломанном
# релизе именно потому, что его пытались починить движением назад.
if grep -qF 'monotonic_gate' "$LIB"; then
    t_ok "monotonic_gate живёт в lib.sh"
else
    t_bad "monotonic_gate в lib.sh нет — прогон проверяет пустоту"
fi

# Внутри switch_symlink проверки быть не должно: через неё ходят оба отката.
awk '/^switch_symlink\(\) \{$/{f=1} f{print} f&&/^\}$/{exit}' "$LIB" > "$TMP/switch.sh"
if [[ -s "$TMP/switch.sh" ]] && grep -qF 'ln -sfn' "$TMP/switch.sh"; then
    t_ok "тело switch_symlink вырезано"
else
    t_bad "тело switch_symlink НЕ вырезано — якорь уехал, случай проверяет пустоту"
fi
grep -qF 'monotonic_gate' "$TMP/switch.sh" \
    && t_bad "проверка внутри switch_symlink — она запретит автооткат" \
    || t_ok "switch_symlink ничего не проверяет: через неё ходит откат"

# release.sh зовёт проверку ровно один раз и ДО переключения current.
CALLS="$(grep -c '^monotonic_gate ' "$REL")"
[[ "$CALLS" == 1 ]] \
    && t_ok "release.sh зовёт проверку один раз" \
    || t_bad "release.sh зовёт проверку $CALLS раз, ожидался 1"
LN_GATE="$(grep -n '^monotonic_gate ' "$REL" | head -1 | cut -d: -f1)"
LN_SWITCH="$(grep -n 'switch_symlink "\$CURRENT" "\$NEW_DIR"' "$REL" | head -1 | cut -d: -f1)"
if [[ -n "$LN_GATE" && -n "$LN_SWITCH" ]] && (( LN_GATE < LN_SWITCH )); then
    t_ok "проверка стоит перед переключением current (строки $LN_GATE и $LN_SWITCH)"
else
    t_bad "проверка не перед переключением current: вызов «$LN_GATE», переключение «$LN_SWITCH»"
fi

# Автооткат внутри release.sh под запрет не попадает.
awk '/^rollback\(\) \{$/{f=1} f{print} f&&/^\}$/{exit}' "$REL" > "$TMP/rollback-fn.sh"
if [[ -s "$TMP/rollback-fn.sh" ]] && grep -qF 'switch_symlink "$CURRENT" "$PREV_TARGET"' "$TMP/rollback-fn.sh"; then
    t_ok "тело rollback() вырезано"
else
    t_bad "тело rollback() НЕ вырезано — якорь уехал, случай проверяет пустоту"
fi
grep -qF 'monotonic_gate' "$TMP/rollback-fn.sh" \
    && t_bad "автооткат внутри release.sh проходит через запрет — он не починит прод" \
    || t_ok "автооткат идёт мимо запрета"

t_case "6a. Разбираются все три файла"
for f in "$LIB" "$REL" "$RB"; do
    if bash -n "$f" 2>"$TMP/synerr"; then
        t_ok "разбирается: ${f#"$KIT/"}"
    else
        t_bad "не разбирается ${f#"$KIT/"}: $(cat "$TMP/synerr")"
    fi
done

# --------------------------------------------------------------------------
printf '\n\033[1mитого: %d прошло, %d провалено\033[0m\n' "$pass" "$fail"
(( fail == 0 )) || exit 1
exit 0
