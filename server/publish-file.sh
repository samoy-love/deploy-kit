#!/usr/bin/env bash
# Публикация ОДНОГО файла в каталог, который nginx раздаёт как есть.
#
# Зачем отдельный скрипт, когда есть release.sh. Релизная механика — каталог
# releases/, симлинк current, юниты, version.json — построена вокруг сервисов
# и сайтов. Установщик лаунчера в неё не помещается сознательно: это один
# файл на четверть гигабайта, который живёт ВНЕ релизов сайта (см. комментарий
# у location /downloads/ в nginx/sites/chillhub-launcher.conf), не имеет ни
# юнита, ни health-проверки, и «выкатить» его значит ровно одно — атомарно
# подменить файл, не порвав ни одного идущего скачивания.
#
#   publish-file.sh --file   /tmp/dk-XXX/ChillHub-Setup.exe \
#                   --sha256 /tmp/dk-XXX/ChillHub-Setup.exe.sha256 \
#                   --dest   /var/www/site-downloads/ChillHub-Setup.exe
#
# Что делает:
#   1. сверяет файл с приехавшей рядом контрольной суммой (обрыв scp не должен
#      доехать до пользователей);
#   2. кладёт копию в целевой каталог под временным именем и атомарно
#      переименовывает в --dest; идущие скачивания дочитывают старый inode;
#   3. прежний файл остаётся жёсткой ссылкой <dest>.prev — мгновенный ручной
#      откат без повторной сборки: mv ChillHub-Setup.exe.prev ChillHub-Setup.exe;
#   4. рядом публикует <dest>.sha256, чтобы скачавший мог проверить файл, а
#      пайплайн — сверить, что прод раздаёт именно эту сборку;
#   5. с --version рядом ложится и <dest>.json — манифест для самообновления
#      клиента: версия, сумма и размер. Приложение на консоли сравнивает с
#      ним свою версию и по нему же проверяет скачанное.
#
# Замок хоста тут НЕ берётся: скрипт не трогает ни релизы, ни nginx, ни
# systemd — только подменяет файл в своём каталоге, и делает это атомарно.
# Очередь выкаток задерживать нечем и незачем.
#
# Код возврата: 0 — опубликовано, 1 — нет (прежний файл не тронут).

set -Eeuo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

FILE=""; SHA_FILE=""; DEST=""; APP=""; VERSION=""
while [[ $# -gt 0 ]]; do
    case "$1" in
        --file)   FILE="$2"; shift 2 ;;
        --sha256) SHA_FILE="$2"; shift 2 ;;
        --dest)   DEST="$2"; shift 2 ;;
        # Цель и версия нужны только событию (docs/events.md): публикация
        # файла сама по себе о них не знает — она знает про путь. Поэтому
        # флаги необязательные: старый вызов без них публикует как раньше,
        # просто молча.
        --app)     APP="$2"; shift 2 ;;
        --version) VERSION="$2"; shift 2 ;;
        # Незнакомый флаг — не повод падать: пайплайн обновляется сам
        # (uses: ...@main), а этот скрипт живёт на хосте и отстаёт.
        *) warn "неизвестный аргумент, пропускаю: $1"; shift ;;
    esac
done

[[ -n "$FILE" ]] || die "нужен --file"
[[ -n "$DEST" ]] || die "нужен --dest"
[[ -f "$FILE" ]] || die "нет файла $FILE"
[[ -s "$FILE" ]] || die "файл $FILE пуст — публиковать нечего"

# --dest приходит аргументом через sudo, и sudoers аргументы сознательно не
# ограничивает — вся граница проходит здесь (см. server/sudoers.d/deploy-kit).
# Требование то же, что у корня выкатки: <разрешённый родитель>/<каталог>/<файл>.
BASE="$(basename -- "$DEST")"
assert_path_component "имя файла в --dest" "$BASE"
[[ "$DEST" == /* ]] || die "--dest должен быть абсолютным путём, получено «$DEST»"
DESTDIR="$(assert_deploy_root "$(dirname -- "$DEST")")"
DEST="$DESTDIR/$BASE"

# --app и --version уезжают в ИМЯ файла события, поэтому проверяются тем же
# assert_path_component, что и всё, из чего собираются пути.
[[ -z "$APP" ]]     || assert_path_component "--app" "$APP"
[[ -z "$VERSION" ]] || assert_path_component "--version" "$VERSION"

# Событие публикации. Обоснование защиты — в шапке notify_event в release.sh:
# отдельный процесс, timeout, гашение любого кода возврата. Файл здесь уже
# опубликован, и уведомление не имеет права превратить успех в ошибку.
DK_NOTIFY="${DK_NOTIFY:-}"
if [[ -z "$DK_NOTIFY" ]]; then
    _dk_dir="$(dirname "${BASH_SOURCE[0]}")"
    if   [[ -f "$_dk_dir/notify.sh" ]];        then DK_NOTIFY="$_dk_dir/notify.sh"
    elif [[ -f "$_dk_dir/../lib/notify.sh" ]]; then DK_NOTIFY="$_dk_dir/../lib/notify.sh"
    fi
fi

notify_event() {
    if [[ ! -f "$DK_NOTIFY" ]]; then
        log "notify.sh не найден — событие «$*» не отправлено"
        return 0
    fi
    # Вызов идёт УЖЕ на сервере — доставать себя же по SSH незачем, событие
    # просто дописывается в журнал напрямую. Без --mode notify.sh молча берёт
    # умолчание "ssh" и требует --host, которого здесь никогда не будет.
    if command -v timeout >/dev/null 2>&1; then
        timeout 30 bash "$DK_NOTIFY" --mode local "$@" </dev/null || warn "событие не отправлено (код $?): $*"
    else
        bash "$DK_NOTIFY" --mode local "$@" </dev/null || warn "событие не отправлено (код $?): $*"
    fi
    return 0
}

log "публикую $BASE в $DESTDIR"

# Сумма проверяется ДО того, как что-либо тронуто: файл шёл через scp, и
# оборванная или побитая доставка обязана остановиться здесь, а не всплыть
# у пользователя, скачавшего установщик наполовину.
GOT=""
if [[ -n "$SHA_FILE" ]]; then
    [[ -f "$SHA_FILE" ]] || die "нет файла контрольной суммы $SHA_FILE"
    need_cmd sha256sum
    WANT="$(awk '{print tolower($1); exit}' "$SHA_FILE")"
    [[ "$WANT" =~ ^[0-9a-f]{64}$ ]] || die "в $SHA_FILE не нашлось контрольной суммы"
    GOT="$(sha256sum -- "$FILE" | cut -d' ' -f1)"
    [[ "$GOT" == "$WANT" ]] \
        || die "контрольная сумма не сошлась: файл побился при доставке (ожидалось $WANT, получено $GOT)"
    ok "контрольная сумма сошлась: $GOT"
else
    warn "запуск без --sha256 — целостность доставки не проверяется"
fi

# Каталога может ещё не быть — первая публикация его и заводит. 0755, чтобы
# nginx (www-data) мог читать.
install -d -m 0755 "$DESTDIR"

# Места нужно на копию файла; .prev места не ест — это жёсткая ссылка на
# прежний inode. Запас 50 МБ — чтобы публикация не выедала диск в ноль.
NEED=$(( $(stat -c%s -- "$FILE") / 1024 / 1024 + 50 ))
HAVE="$(free_mb "$DESTDIR")"
(( HAVE > NEED )) || die "мало места в $DESTDIR: нужно ~${NEED} МБ, свободно ${HAVE} МБ"

# Временные имена начинаются с точки: location /downloads/ раздаёт из каталога
# всё подряд, а недокопированный файл не должен быть скачиваемым даже у того,
# кто угадает имя. mktemp даёт 0600 и непредсказуемый хвост.
TMP=""; TMPSHA=""; TMPJSON=""
cleanup() { rm -f -- "$TMP" "$TMPSHA" "$TMPJSON"; }
trap cleanup EXIT

TMP="$(mktemp "$DESTDIR/.$BASE.new.XXXXXXXX")"
cp -- "$FILE" "$TMP"
chmod 0644 "$TMP"

# Прежний файл переживает подмену жёсткой ссылкой, а не копией: ссылка
# мгновенна и не удваивает занятое место. mv -f поверх существующего имени —
# атомарная замена внутри одной ФС: у скачивающих в этот момент остаётся
# старый inode, и их загрузка дочитывается целой.
#
# Проверки существования — `if`, а не `[[ ]] &&`: скрипт идёт под `set -e`,
# и одиночная конструкция «условие && действие» с ложным условием — это
# ненулевой код всей строки, то есть смерть скрипта на первой публикации,
# когда подменять ещё нечего.
if [[ -f "$DEST" ]]; then
    ln -f -- "$DEST" "$DEST.prev"
fi
mv -f -- "$TMP" "$DEST"
TMP=""

# Сумма публикуется ПОСЛЕ файла и нормализованной строкой «<sha>  <имя>»:
# приехавший .sha256 мог называть файл временным именем из scp, а проверять
# его будут против имени, под которым файл лежит здесь.
if [[ -n "$GOT" ]]; then
    TMPSHA="$(mktemp "$DESTDIR/.$BASE.sha256.XXXXXXXX")"
    printf '%s  %s\n' "$GOT" "$BASE" > "$TMPSHA"
    chmod 0644 "$TMPSHA"
    if [[ -f "$DEST.sha256" ]]; then
        ln -f -- "$DEST.sha256" "$DEST.sha256.prev"
    fi
    mv -f -- "$TMPSHA" "$DEST.sha256"
    TMPSHA=""
fi

# Манифест самообновления. Только при --version: без версии сравнивать
# клиенту не с чем, а выдумывать её нельзя. Атомарно, как и всё остальное.
if [[ -n "$VERSION" && -n "$GOT" ]]; then
    TMPJSON="$(mktemp "$DESTDIR/.$BASE.json.XXXXXXXX")"
    printf '{"version":"%s","file":"%s","sha256":"%s","size":%s}\n' \
        "$VERSION" "$BASE" "$GOT" "$(stat -c%s -- "$DEST")" > "$TMPJSON"
    chmod 0644 "$TMPJSON"
    if [[ -f "$DEST.json" ]]; then
        ln -f -- "$DEST.json" "$DEST.json.prev"
    fi
    mv -f -- "$TMPJSON" "$DEST.json"
    TMPJSON=""
fi

SIZE="$(du -h -- "$DEST" | cut -f1)"
ok "опубликован $DEST ($SIZE)"
if [[ -f "$DEST.prev" ]]; then
    log "прежняя версия лежит рядом: $DEST.prev (откат: mv поверх основного имени)"
fi

# Событие — после подмены, когда пользователи уже качают новый файл. Без --app
# и --version его не собрать: обязательные поля выдумывать нельзя, а имя файла
# на роль версии не годится — оно у установщика постоянное.
if [[ -n "$APP" && -n "$VERSION" ]]; then
    notify_event --kind published --app "$APP" --version "$VERSION"
else
    log "без --app и --version событие о публикации не отправляется"
fi
exit 0
