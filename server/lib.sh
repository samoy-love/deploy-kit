#!/usr/bin/env bash
# Общие функции серверных скриптов deploy-kit.
# Подключается через `source`, самостоятельно не запускается.

set -Eeuo pipefail

RED=$'\033[31m'; GRN=$'\033[32m'; YEL=$'\033[33m'; DIM=$'\033[2m'; RST=$'\033[0m'
[[ -t 1 ]] || { RED=''; GRN=''; YEL=''; DIM=''; RST=''; }

log()  { printf '%s[%s]%s %s\n' "$DIM" "$(TZ=Europe/Moscow date '+%H:%M:%S')" "$RST" "$*"; }
ok()   { printf '%s✓%s %s\n' "$GRN" "$RST" "$*"; }
warn() { printf '%s!%s %s\n' "$YEL" "$RST" "$*" >&2; }
die_code() { local c="$1"; shift; printf '%s✗%s %s\n' "$RED" "$RST" "$*" >&2; exit "$c"; }
die()  { die_code 1 "$@"; }

# Отдельный код возврата для отказа шлюза. Вызывающая сторона (bin/deploy,
# workflow) по нему отличает «шлюз не пустил, прод цел» от «выкатка сломалась
# посреди процесса» — в логе это два совершенно разных события, а раньше оба
# выглядели как «упало непонятно почему».
GATE_REJECT=3

# --- мьютекс на весь хост -------------------------------------------------
#
# На этом сервере живут четыре проекта из разных репозиториев, и каждый
# катится своим workflow. Concurrency в GitHub Actions разводит выкатки
# только внутри репозитория: две из разных репозиториев спокойно начнутся
# одновременно и станут одновременно перезагружать nginx или двигать
# симлинки. Блокировка одна на хост, а не на приложение.
LOCK_FILE=/var/lock/deploy-kit.lock
LOCK_WAIT=${LOCK_WAIT:-600}

acquire_lock() {
    exec 9>"$LOCK_FILE" || die "не открыть $LOCK_FILE"
    if ! flock -w "$LOCK_WAIT" 9; then
        die "не дождались очереди за ${LOCK_WAIT}s — на хосте идёт другая выкатка"
    fi
    log "очередь на хосте занята нами (pid $$)"
}

# --- вспомогательное ------------------------------------------------------

need_cmd() { command -v "$1" >/dev/null 2>&1 || die "нет команды $1"; }

# --- Проверка путей, приходящих аргументами ---------------------------------
#
# Серверные скрипты запускаются через sudo, и sudoers аргументы сознательно НЕ
# ограничивает — см. server/sudoers.d/deploy-kit: «Проверку аргументов делают
# сами скрипты». Значит, вся граница между «правами на выкатку» и «root на
# хосте» проходит ровно здесь. Проверки обязаны падать ЗАКРЫТЫМИ: всё, что не
# разобрано однозначно, — отказ, а не «наверное, можно».
#
# Что именно тут ловится. `rm -rf "$ROOT/releases/$VERSION"`, `tar -xzf ... -C`
# и `install ... /etc/nginx/...` выполняются от root, и одного `..` в имени
# релиза или в корне выкатки достаточно, чтобы увести их в любую точку ФС.
# Поэтому имя релиза обязано быть ОДНОЙ составляющей пути, а корень выкатки —
# лежать внутри известного каталога, причём проверяется он после физического
# разворачивания (симлинк не должен уводить запись мимо проверки).

# Родительские каталоги, внутри которых вообще может жить корень выкатки.
# Список короткий намеренно: он покрывает все существующие цели (/opt/<сервис>
# и /var/www/<сайт>), а новая площадка — это осознанная правка здесь, а не
# сюрприз, приехавший аргументом.
DEPLOY_ROOT_PARENTS=(/opt /var/www)

# Одна составляющая пути: имя релиза, приложения, каталога. Ни слэша, ни «..»,
# ни ведущей точки, ни пустоты — из такого имени выйти вверх невозможно.
assert_path_component() {
    local what="$1" v="${2-}"
    [[ -n "$v" ]] || die "$what: пустое значение"
    [[ "$v" != *"/"* ]] || die "$what не может содержать «/»: «$v»"
    [[ "$v" != *".."* ]] || die "$what не может содержать «..»: «$v»"
    [[ "$v" != .* ]] || die "$what не может начинаться с точки: «$v»"
    [[ "$v" =~ ^[A-Za-z0-9._+-]+$ ]] \
        || die "$what: допустимы только буквы, цифры и «._+-», получено «$v»"
}

# Корень выкатки. Печатает канонический путь, при любом сомнении — die.
#
# Требование жёсткое и намеренно негибкое: <разрешённый родитель>/<одна
# составляющая>. Всё, что глубже, — отказ; проверять вложенность честно
# дороже, чем она стоит, а все одиннадцать существующих целей описаны именно
# так (/opt/snakes, /var/www/samoy.love).
assert_deploy_root() {
    local root="${1-}" parent base p
    [[ -n "$root" ]] || die "не задан --root"
    [[ "$root" == /* ]] || die "--root должен быть абсолютным путём, получено «$root»"
    [[ "$root" != *".."* ]] || die "в --root недопустимо «..»: «$root»"
    root="${root%/}"
    base="$(basename -- "$root")"
    assert_path_component "имя каталога в --root" "$base"
    # pwd -P разворачивает и «.», и симлинки: сравнивается физический путь.
    parent="$(cd "$(dirname -- "$root")" 2>/dev/null && pwd -P || true)"
    [[ -n "$parent" ]] || die "каталога $(dirname -- "$root") не существует"
    for p in "${DEPLOY_ROOT_PARENTS[@]}"; do
        [[ "$parent" == "$p" ]] || continue
        printf '%s/%s' "$parent" "$base"
        return 0
    done
    die "--root допустим только одним уровнем внутри ${DEPLOY_ROOT_PARENTS[*]}, получено «$root»"
}

# Свободное место в мегабайтах для указанного пути.
free_mb() { df -Pm "$1" | awk 'NR==2 {print $4}'; }

human_ts() { TZ=Europe/Moscow date '+%Y%m%d-%H%M%S'; }

# Симлинк current -> releases/<версия>; меняется атомарно через временный
# линк и mv -T, иначе между rm и ln есть окно, когда пути не существует.
switch_symlink() {
    local link="$1" target="$2" tmp
    tmp="${link}.new.$$"
    ln -sfn "$target" "$tmp"
    mv -T "$tmp" "$link"
}

# Удаляет старые релизы, оставляя последние KEEP штук.
prune_releases() {
    local dir="$1" keep="${2:-5}" n
    [[ -d "$dir" ]] || return 0
    n=$(find "$dir" -mindepth 1 -maxdepth 1 -type d | wc -l)
    (( n > keep )) || return 0
    find "$dir" -mindepth 1 -maxdepth 1 -type d -printf '%T@ %p\n' \
        | sort -n | head -n "$(( n - keep ))" | cut -d' ' -f2- \
        | while read -r old; do
            log "удаляю старый релиз $(basename "$old")"
            rm -rf "$old"
        done
}

# --- Юниты systemd из релиза ----------------------------------------------
#
# Юнит лежит в git, а на сервер попадал руками, один раз, при установке.
# Дальше файл в репозитории и файл на машине жили каждый своей жизнью:
# правка ExecStart уезжала в main, зелёный деплой рапортовал об успехе, а
# служба продолжала запускаться со старыми аргументами. Так статус-страница
# полдня читала конфиг годовой давности при свежем релизе на диске.
#
# Ставим только то, что реально изменилось: daemon-reload на каждую выкатку
# ради неизменившегося файла — лишний повод дёрнуть systemd.
#
# Живёт здесь, а не в release.sh, потому что нужна обоим путям отката. Ручной
# откат (rollback.sh) обязан вернуть юниты так же, как это делает автоматический
# внутри release.sh: иначе на старом коде остаётся ExecStart от нового релиза —
# ровно тот случай, ради которого функция и появилась.
#
# ДОПОЛНЕНИЯ (drop-in). Кроме плоских юнитов релиз может везти
# `systemd/<юнит>.d/<имя>.conf` — кусок настроек существующего юнита, который
# обязан лечь в `/etc/systemd/system/<юнит>.d/<имя>.conf`. Плоский глоб такой
# файл не ловит: он лежит на уровень глубже. Довезти дополнение до сервера и не
# поставить — это файл в каталоге релиза, о котором systemd не знает, при
# зелёной выкатке: ровно то самое «зелёный деплой, который ничего не делает»,
# ради чего функция и написана.
#
# Дополнение НЕ включают (`enable`) и не запускают (`start`). Это не юнит: у
# него нет ни [Install], ни собственного состояния в systemd, и
# `systemctl enable snakes.service.d/10-x.conf` — бессмыслица. Чтобы дополнение
# оказалось прочитанным, хватает daemon-reload, который тут и так делается;
# чтобы оно ПОДЕЙСТВОВАЛО, надо перезапустить сам юнит. Свой юнит выкатка
# перезапускает сама (release.sh, `--unit`), про чужой мы говорим вслух —
# молча оставить службу со старой настройкой значило бы то же бездействие.
#
# УДАЛЁННОЕ ДОПОЛНЕНИЕ. Файл, стёртый из git, сам собой из /etc не исчезнет.
# Удалять его автоматически мы не будем: install_units не помнит, что ставила
# в прошлый раз, а в `<юнит>.d` законно лежат чужие файлы — от пакета, от руки,
# от соседней цели. Стереть от root файл, происхождение которого не доказано, —
# способ оставить службу без запуска, а это дороже любого устаревшего
# override. Поэтому лишнее НАЗЫВАЕТСЯ: список того, что есть на хосте и чего
# нет в релизе, уходит в предупреждение — и делается это до проверки «что-то
# изменилось», потому что удалённое дополнение как раз и выглядит как выкатка,
# в которой не изменилось ничего. Та же строка появится при откате на релиз,
# который нового дополнения ещё не знал, — и это ровно то, что человеку в тот
# момент нужно услышать.
#
# У разбора есть честная граница, и её лучше знать заранее: он идёт по тем
# каталогам `<юнит>.d`, которые ЕСТЬ В РЕЛИЗЕ. Если из git убрали последний
# .conf, каталог исчезает вместе с ним, и на хосте не остаётся ничего, что
# указывало бы на нас, — такой файл не будет ни удалён, ни назван. Список
# того, что мы когда-то поставили, для этого пришлось бы держать на хосте
# отдельным файлом; заводить учётную запись состояния в /etc/systemd/system
# ради этого случая дороже, чем он стоит. Для плоских юнитов разбора нет и
# быть не может вовсе: в /etc/systemd/system лежат все юниты хоста, и понять,
# какие из них когда-то приехали отсюда, неоткуда.

# Каталог назначения одной переменной, а не строкой по месту: адресов стало
# четыре (юнит, дополнение, каталог дополнения, разбор остатков), и разъехаться
# они не должны. Присваивание безусловное — значение из окружения сюда НЕ
# попадает: функция работает от root, и путь установки юнитов не то, что
# отдают наружу. Прогону ci/units-test.sh хватает переопределения после
# `source`.
SYSTEMD_DIR=/etc/systemd/system

install_units() {
    local dir="$1/systemd" changed=0
    [[ -d "$dir" ]] || return 0

    # Разбор каталога — одним куском под nullglob, дальше только обход
    # массивов. Иначе ранний `return 1` из середины цикла оставил бы nullglob
    # включённым у вызывающей стороны.
    #
    # Всё, что разбор не узнал, попадает в unknown и НАЗЫВАЕТСЯ вслух.
    # Отдельная ветка нужна из-за опечатки: `snakes.serivce.d` под глоб не
    # подходит, а значит файл не поставится и никто об этом не скажет — файл
    # в артефакте есть, выкатка зелёная, systemd про настройку не знает.
    # Молчаливого пропуска здесь быть не должно ни в каком виде: юниты, для
    # которых мы не умеем ни enable, ни start (*.target, *.path, *.mount),
    # тоже называются, а не проглатываются.
    local flat=() dropins=() stale=() unknown=() h c ud
    shopt -s nullglob
    for h in "$dir"/*; do
        case "$h" in
            *.service|*.timer|*.socket)
                if [[ -f "$h" ]]; then flat+=( "$h" ); else unknown+=( "${h#"$dir"/}" ); fi ;;
            *.service.d|*.timer.d|*.socket.d)
                if [[ ! -d "$h" ]]; then unknown+=( "${h#"$dir"/}" ); continue; fi
                ud="$(basename "$h")"
                for c in "$h"/*; do
                    if [[ -f "$c" && "$c" == *.conf ]]; then
                        dropins+=( "$c" )
                    else
                        unknown+=( "${c#"$dir"/}" )
                    fi
                done
                # Что лежит в <юнит>.d на хосте, но в релиз не приехало.
                # Считается ДО установки: свои файлы в этот список не попадут
                # по построению.
                for c in "$SYSTEMD_DIR/$ud"/*.conf; do
                    [[ -f "$h/$(basename "$c")" ]] || stale+=( "$ud/$(basename "$c")" )
                done ;;
            *)  unknown+=( "${h#"$dir"/}" ) ;;
        esac
    done
    shopt -u nullglob

    local f name rel unit installed=() touched=()
    for f in "${flat[@]}"; do
        name="$(basename "$f")"
        if cmp -s "$f" "$SYSTEMD_DIR/$name"; then
            continue
        fi
        # Явное || return: функция вызывается через `|| rollback`, а в таком
        # контексте set -e внутри неё не действует, и провал install молча
        # прошёл бы дальше.
        install -m 0644 "$f" "$SYSTEMD_DIR/$name" || return 1
        log "юнит обновлён: $name"
        installed+=("$name")
        changed=1
    done

    for f in "${dropins[@]}"; do
        rel="${f#"$dir"/}"                      # snakes.service.d/10-metrics.conf
        unit="${rel%%/*}"; unit="${unit%.d}"    # snakes.service
        if cmp -s "$f" "$SYSTEMD_DIR/$rel"; then
            continue
        fi
        # Каталога <юнит>.d на хосте может не быть вовсе: дополнение приезжает
        # к юниту, который ставили руками и давно. Создаём сами — и так же
        # явно проверяем результат, по той же причине, что и install ниже.
        #
        # Только СОЗДАЁМ: `install -d -m 0755` на существующий каталог молча
        # переставляет ему права, а это чужой каталог в /etc, куда свои
        # дополнения кладёт и пакет, и рука администратора. Трогать его режим
        # мы не подряжались.
        [[ -d "$SYSTEMD_DIR/${rel%/*}" ]] \
            || install -d -m 0755 "$SYSTEMD_DIR/${rel%/*}" || return 1
        install -m 0644 "$f" "$SYSTEMD_DIR/$rel" || return 1
        log "дополнение юнита обновлено: $rel"
        touched+=("$unit")
        changed=1
    done

    if (( ${#unknown[@]} )); then
        warn "в systemd/ лежит то, чего выкатка не ставит: ${unknown[*]} — ставятся *.service, *.timer, *.socket и дополнения <юнит>.d/*.conf; проверьте имя, systemd этих файлов не увидит"
    fi
    if (( ${#stale[@]} )); then
        warn "в $SYSTEMD_DIR есть дополнения, которых нет в релизе: ${stale[*]} — сами они не удалятся, снимите руками, если они лишние"
    fi

    (( changed )) || return 0
    systemctl daemon-reload

    # Автозапуск включаем сами: юнит, приехавший впервые, иначе не переживёт
    # перезагрузку сервера, и об этом узнают в худший момент. Таймеры и
    # сокеты запускаем сразу — их, в отличие от службы, ниже никто не
    # перезапустит.
    for name in "${installed[@]}"; do
        case "$name" in
            *.timer|*.socket) systemctl enable --now "$name" || warn "не включён: $name" ;;
            *)                systemctl enable "$name" >/dev/null 2>&1 || true ;;
        esac
    done

    # Юнит, который эта выкатка перезапускает сама. `UNIT=snakes` без суффикса
    # systemd принимает наравне с `snakes.service`, поэтому сравниваем в одной
    # форме, иначе предупреждение ниже пугало бы на ровном месте.
    local self="${UNIT-}"
    [[ -z "$self" || "$self" == *.* ]] || self="$self.service"

    local reported=()
    for unit in "${touched[@]}"; do
        [[ " ${reported[*]} " == *" $unit "* ]] && continue
        reported+=("$unit")
        # Дополнение к юниту, которого на хосте нет, systemd просто не с чем
        # склеить: файл лежит, толку ноль. Так выглядит и переименованный
        # юнит, и юнит, который когда-то ставили руками и потеряли, — сам по
        # себе этот случай ничем больше не виден.
        systemctl cat -- "$unit" >/dev/null 2>&1 \
            || warn "юнита $unit на хосте не видно — дополнение к нему ни на что не влияет, проверьте имя каталога"
        [[ "$unit" == "$self" ]] \
            || warn "дополнение изменилось, но $unit эта выкатка не перезапускает — примените вручную: systemctl restart $unit"
    done
    ok "юниты systemd применены"
}

# Ждёт HTTP 200 с ретраями. Возвращает 1, если не дождались.
wait_http() {
    local url="$1" tries="${2:-10}" pause="${3:-3}" code
    for ((i = 1; i <= tries; i++)); do
        code=$(curl -sL -o /dev/null -w '%{http_code}' --max-time 15 "$url" || true)
        [[ "$code" == "200" ]] && { ok "$url отвечает 200 (попытка $i)"; return 0; }
        log "попытка $i/$tries: $url -> $code"
        sleep "$pause"
    done
    return 1
}

# Сверяет версию, которую отдаёт сервис, с ожидаемой.
#
# Это главная проверка выкатки: код 200 подтверждает лишь то, что что-то
# отвечает, а расхождение версий ловит случай «деплой прошёл зелёным, а
# файлы остались старые» — самый неприятный, потому что выглядит успехом.
check_version() {
    local url="$1" want="$2" got
    got=$(curl -sL --max-time 15 "$url" 2>/dev/null | sed -n 's/.*"version"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p' | head -1)
    # Пустой ответ — это провал, а не «нечего сверять». Раньше здесь стоял
    # warn с return 0, и релиз без version.json уезжал зелёным: /version.json
    # отдавал 404 часами, потому что единственный, кто мог это заметить,
    # сам себе это и прощал. Цели, которые version.json не раздают, приходят
    # сюда без VERSION_URL (--no-version-file) и проверяются по симлинку.
    [[ -z "$got" ]] && { warn "$url не отдал version — релиз не подтверждает себя"; return 1; }
    [[ "$got" == "$want" ]] && { ok "версия совпала: $got"; return 0; }
    warn "версия НЕ совпала: ожидали $want, получили $got"
    return 1
}

# --- версионный шлюз ------------------------------------------------------
#
# Два случая из практики, ради которых он существует:
#   1. релиз выложили без version.json — /version.json отдавал 404 часами,
#      и никто этого не заметил, потому что «деплой прошёл зелёным»;
#   2. старая сборка уехала под видом новой — симлинк переключился на релиз
#      старше текущего, и на проде молча откатилась функциональность.
# Оба ловятся до переключения симлинка: прод при отказе остаётся нетронутым.

# Метки, которые не являются версией. Появляются, когда сборка шла мимо
# пайплайна и подстановка версии просто не сработала.
VERSION_PLACEHOLDERS=" dev unknown none null nil latest head local snapshot "

version_is_placeholder() {
    local v="${1,,}"
    [[ -z "${v//[[:space:]]/}" ]] && return 0
    [[ "$VERSION_PLACEHOLDERS" == *" $v "* ]]
}

# Таймштамп из имени релиза (release-20260802-134500-abc1234) как 14 цифр:
# в таком виде лексикографический порядок совпадает с хронологическим.
version_ts() {
    local m
    m=$(grep -oE '[0-9]{8}-[0-9]{6}' <<<"$1" | head -1)
    [[ -n "$m" ]] || return 1
    printf '%s' "${m/-/}"
}

# Разбор семверного тега: «мажор минор патч предрелиз».
version_semver() {
    [[ "$1" =~ ^[vV]?([0-9]+)\.([0-9]+)\.([0-9]+)(-([0-9A-Za-z.-]+))?$ ]] || return 1
    printf '%s %s %s %s' "${BASH_REMATCH[1]}" "${BASH_REMATCH[2]}" "${BASH_REMATCH[3]}" "${BASH_REMATCH[5]}"
}

# Сравнивает две версии: newer | same | older | incomparable.
#
# Схем ровно две — таймштамповая и семверная, — и сравниваются они только
# сами с собой. Смешивать нельзя: у v1.4.0 нет даты, у release-2026… нет
# номера, и любое «разумное умолчание» здесь означало бы угадывание.
compare_versions() {
    local new="$1" cur="$2" n_ts c_ts n_sv c_sv pair
    [[ "$new" == "$cur" ]] && { echo same; return 0; }

    n_ts=$(version_ts "$new") || n_ts=""
    c_ts=$(version_ts "$cur") || c_ts=""
    if [[ -n "$n_ts" && -n "$c_ts" ]]; then
        if   (( 10#$n_ts > 10#$c_ts )); then echo newer
        elif (( 10#$n_ts < 10#$c_ts )); then echo older
        else echo same    # секунда одна, коммиты разные — считаем повтором
        fi
        return 0
    fi

    n_sv=$(version_semver "$new") || n_sv=""
    c_sv=$(version_semver "$cur") || c_sv=""
    if [[ -n "$n_sv" && -n "$c_sv" ]]; then
        local na nb nc npre ca cb cc cpre
        read -r na nb nc npre <<<"$n_sv"
        read -r ca cb cc cpre <<<"$c_sv"
        for pair in "$na $ca" "$nb $cb" "$nc $cc"; do
            # shellcheck disable=SC2086
            set -- $pair
            (( $1 > $2 )) && { echo newer; return 0; }
            (( $1 < $2 )) && { echo older; return 0; }
        done
        # Триплеты равны — решает предрелизная часть: v1.4.0-rc1 старше
        # самого v1.4.0 быть не может.
        [[ -z "$npre" && -n "$cpre" ]] && { echo newer; return 0; }
        [[ -n "$npre" && -z "$cpre" ]] && { echo older; return 0; }
        [[ "$npre" > "$cpre" ]] && { echo newer; return 0; }
        [[ "$npre" < "$cpre" ]] && { echo older; return 0; }
        echo same; return 0
    fi

    echo incomparable
}

# Что сейчас на проде.
#
# Основной источник — /version.json: он показывает, что сервис реально
# отдаёт наружу, а не что лежит в каталоге. Имя каталога из симлинка —
# запасной источник и единственный для целей с WRITE_VERSION_FILE=0
# (морда админки version.json не раздаёт, и требовать его от неё бессмысленно).
# Откуда взята версия прода — для сообщений шлюза.
# Читается вызывающим release.sh после version_gate — shellcheck не видит
# использования через source и считает переменную мёртвой.
export LIVE_VERSION_SOURCE=""

current_live_version() {
    local url="$1" link="$2" got=""
    LIVE_VERSION_SOURCE=""
    if [[ -n "$url" ]]; then
        got=$(curl -sL --max-time 15 "$url" 2>/dev/null \
              | sed -n 's/.*"version"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p' | head -1)
        if [[ -n "$got" ]]; then
            LIVE_VERSION_SOURCE="$url"
        else
            warn "$url не отдал version — беру версию из симлинка current"
        fi
    fi
    if [[ -z "$got" && -L "$link" ]]; then
        got=$(basename "$(readlink -f "$link")")
        LIVE_VERSION_SOURCE="симлинк current"
    fi
    printf '%s' "$got"
}

# Решение шлюза. Отказ = выход с GATE_REJECT, симлинк не тронут.
version_gate() {
    local new="$1" cur="$2" allow="${3:-0}" src="${4:-}"
    local hint="Осознанный повтор (перевыкатка после ручной порчи каталога): --allow-same-version"

    if version_is_placeholder "$new"; then
        die_code "$GATE_REJECT" "версия не задана или бессмысленна: «$new». Релиз без версии не едет"
    fi
    if [[ -z "$cur" ]]; then
        ok "шлюз: на проде релизов нет, выкатываю $new"
        return 0
    fi

    case "$(compare_versions "$new" "$cur")" in
        newer)
            ok "шлюз: $new новее, чем на проде ($cur$src)" ;;
        same)
            (( allow )) && { warn "шлюз: версия $new уже на проде$src, но задан --allow-same-version — продолжаю"; return 0; }
            die_code "$GATE_REJECT" "версия $new уже на проде$src — выкатка отменена, симлинк не тронут. $hint" ;;
        older)
            (( allow )) && { warn "шлюз: $new старше, чем на проде ($cur$src), но задан --allow-same-version — продолжаю"; return 0; }
            die_code "$GATE_REJECT" "версия $new СТАРШЕ той, что на проде ($cur$src) — это уезжающая под видом новой старая сборка. Выкатка отменена, симлинк не тронут. Нужен откат — rollback.sh. $hint" ;;
        *)
            (( allow )) && { warn "шлюз: $new и $cur$src несравнимы, но задан --allow-same-version — продолжаю"; return 0; }
            die_code "$GATE_REJECT" "не могу сравнить $new с тем, что на проде ($cur$src): разные схемы версий. Молча пропустить нельзя — подтвердите явно. $hint" ;;
    esac
}

# Проверяет, что соседние сайты живы. Nginx общий, и ошибка в своём конфиге
# роняет чужие домены — эта проверка ловит именно такие случаи.
check_neighbours() {
    local failed=0 code
    for host in "$@"; do
        code=$(curl -sL -o /dev/null -w '%{http_code}' --max-time 15 "https://$host/" || true)
        if [[ "$code" == "200" || "$code" == "301" || "$code" == "302" ]]; then
            ok "сосед $host: $code"
        else
            warn "сосед $host: $code"
            failed=1
        fi
    done
    return $failed
}
